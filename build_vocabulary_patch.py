"""Build common_ingredients_patch.csv: INCI names that occur in the
ground-truth labels of at least --min-products different products but are
missing from ingredient_master_dataset_fixed.csv (compared case-insensitively).

The main INCI database lacks many of the most common real-label names
(Glycerin, Niacinamide, Aqua, ...); this patch fills that gap. Note the patch
is derived from the same labels used for evaluation -- see the 5-fold
cross-validated check of this rule before reporting it as unbiased.

Each name is written in its most frequent spelling across the labels, and
names are ordered by how many products contain them (most common first).
The committed file was generated by an unsaved one-off script; this rebuild
gives the same 199 names with identical spelling, but the order among names
with equal product counts differs. Order does not affect matching (verified:
identical fuzzy output on all 216 "original" images).

Usage:
  python build_vocabulary_patch.py --check        # rebuild and diff against the existing file
  python build_vocabulary_patch.py                # overwrite common_ingredients_patch.csv
  python build_vocabulary_patch.py --min-products 2 --out results/patch_min2.csv
"""
import argparse
import csv
import glob
import os
from collections import Counter, defaultdict

import ocr_core as core


def build_patch(min_products, label_paths=None):
    """label_paths: the label files to count names in (default: all of them)."""
    main_db = {n.lower() for n in core._load_names(core.INCI_DB_PATH)}
    product_count = Counter()
    spellings = defaultdict(Counter)
    if label_paths is None:
        label_paths = glob.glob(os.path.join(core.LABEL_DIR, "label*.txt"))
    for path in sorted(label_paths):
        names, _ = core.load_reference_text(path)
        seen = set()
        for name in names:
            name = name.strip()
            key = name.lower()
            spellings[key][name] += 1
            if key not in seen:
                seen.add(key)
                product_count[key] += 1

    # most_common() keeps first-seen order among ties (labels read in sorted file order).
    keys = [k for k, c in product_count.most_common() if c >= min_products and k not in main_db]
    return [spellings[k].most_common(1)[0][0] for k in keys]


def write_patch(path, names):
    with open(path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(["inci_name"])
        writer.writerows([n] for n in names)


def check(names):
    existing = core._load_names(core.INCI_PATCH_PATH)
    print(f"rebuilt: {len(names)} names, existing file: {len(existing)} names")
    rebuilt_l, existing_l = {n.lower() for n in names}, {n.lower() for n in existing}
    only_new = sorted(rebuilt_l - existing_l)
    only_old = sorted(existing_l - rebuilt_l)
    old_spelling = {n.lower(): n for n in existing}
    spelling_diff = [(old_spelling[n.lower()], n) for n in names
                     if n.lower() in old_spelling and old_spelling[n.lower()] != n]
    order_same = [n.lower() for n in names] == [n.lower() for n in existing]
    print(f"same set of names (case-insensitive): {not only_new and not only_old}")
    print(f"same spelling for every name: {not spelling_diff}")
    print(f"same order: {order_same}")
    for n in only_new[:20]:
        print(f"  only in rebuilt: {n}")
    for n in only_old[:20]:
        print(f"  only in existing: {n}")
    for old, new in spelling_diff[:20]:
        print(f"  spelling: existing {old!r} vs rebuilt {new!r}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--min-products", type=int, default=5,
                        help="Minimum number of products a name must appear in (default: 5)")
    parser.add_argument("--out", default=core.INCI_PATCH_PATH, help="Output CSV path")
    parser.add_argument("--check", action="store_true",
                        help="Only compare the rebuilt list with the existing patch file; write nothing")
    args = parser.parse_args()

    names = build_patch(args.min_products)
    if args.check:
        check(names)
        return
    write_patch(args.out, names)
    print(f"Wrote {len(names)} names to {args.out}")


if __name__ == "__main__":
    main()
